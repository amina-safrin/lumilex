export function getChoiceVisual(choiceText) {
  if (!choiceText) return { icon: "🌟", label: "", bg: "#f0fdf4" };
  const str = String(choiceText).trim();
  if (CHOICE_VISUALS[str]) return CHOICE_VISUALS[str];

  // Case-insensitive match
  const foundKey = Object.keys(CHOICE_VISUALS).find(
    (k) => k.toLowerCase() === str.toLowerCase()
  );
  if (foundKey) return CHOICE_VISUALS[foundKey];

  return { icon: "🌟", label: str, bg: "#f0fdf4" };
}
